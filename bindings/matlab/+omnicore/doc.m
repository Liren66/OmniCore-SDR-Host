function file = doc(topic)
%DOC Open the OmniCoreSDR documentation in the help browser.
%   omnicore.doc opens the start page. omnicore.doc(TOPIC) opens the page for a class, function,
%   method or topic, for example 'Device', 'omnicore.RxStream', 'receive', 'setTime',
%   'examples', 'errors', 'streaming', 'time', 'formats' or 'simulink' (case-insensitive).
%   FILE = omnicore.doc(...) returns the page's file name without opening it.
%
%   With the toolbox folder on the MATLAB path the pages are also listed under Supplemental
%   Software on the help browser's start page (registered by info.xml).
%
%   See also omnicore.Device, omnicore.findDevices.

root = fullfile(fileparts(fileparts(mfilename('fullpath'))), 'doc');
page = 'index.html';
if nargin > 0
    page = page_for(lower(char(topic)));
end
target = fullfile(root, page);
if ~exist(target, 'file')
    error('omnicore:InvalidArgument', 'No OmniCoreSDR documentation at %s', target);
end
if nargout > 0
    file = target;
    return
end
web(target, '-helpbrowser');
end

function page = page_for(topic)
topic = regexprep(topic, '^omnicore\.', '');
pages = { ...
    {'', 'index', 'home'}, 'index.html'; ...
    {'start', 'getting_started', 'gettingstarted', 'install'}, 'getting_started.html'; ...
    {'examples', 'example', 'demos'}, 'examples.html'; ...
    {'functions', 'reference', 'contents'}, 'functions.html'; ...
    {'device'}, 'omnicore.Device.html'; ...
    {'configure', 'device.configure'}, 'omnicore.Device.configure.html'; ...
    {'receive', 'device.receive'}, 'omnicore.Device.receive.html'; ...
    {'transmit', 'device.transmit'}, 'omnicore.Device.transmit.html'; ...
    {'transmitrepeat', 'stoptransmit', 'istransmitting'}, 'omnicore.Device.transmitRepeat.html'; ...
    {'time', 'timeticks', 'settime', 'lastpps', 'pps'}, 'omnicore.Device.time.html'; ...
    {'info', 'status', 'events'}, 'omnicore.Device.status.html'; ...
    {'rxstream', 'read', 'start'}, 'omnicore.RxStream.html'; ...
    {'txstream', 'write'}, 'omnicore.TxStream.html'; ...
    {'receiver'}, 'omnicore.Receiver.html'; ...
    {'transmitter'}, 'omnicore.Transmitter.html'; ...
    {'finddevices'}, 'omnicore.findDevices.html'; ...
    {'version'}, 'omnicore.version.html'; ...
    {'doc'}, 'omnicore.doc.html'; ...
    {'formats', 'data_formats', 'scaling'}, 'data_formats.html'; ...
    {'streaming', 'duplex', 'overflow'}, 'streaming.html'; ...
    {'time_pps', 'timestamps'}, 'time_pps.html'; ...
    {'simulink'}, 'simulink.html'; ...
    {'errors', 'warnings', 'error'}, 'errors.html'};
for k = 1:size(pages, 1)
    if any(strcmp(topic, pages{k, 1}))
        page = pages{k, 2};
        return
    end
end
error('omnicore:InvalidArgument', 'No OmniCoreSDR documentation page for ''%s''; try omnicore.doc', topic);
end
